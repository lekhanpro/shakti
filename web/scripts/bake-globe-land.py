"""Bake the dot-matrix globe's land mask into a compact source module.

One-time generator. Its output, lib/globe-land.ts, is committed, so the landing
page requests no Earth texture at run time.

Source: public/textures/earth-specular.jpg. On that map open water is painted
bright and land dark, which makes it a clean land/ocean mask (verified against
eight known land and water coordinates before this script was written).

Encoding: candidate dots are a Fibonacci sphere -- a deterministic spiral that
spreads points evenly over the sphere with no rings and no polar bunching. Point
i of N is a pure function of i, so only one bit per point ships (land or water)
and lib/globe-land.ts regenerates the same spiral and walks the same bits in the
same order. The whole planet costs ~1.6 KB instead of a 223 KB JPEG.

Run (from web/):  py scripts/bake-globe-land.py
"""

from __future__ import annotations

import base64
import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "public" / "textures" / "earth-specular.jpg"
OUT_TS = ROOT / "lib" / "globe-land.ts"
PREVIEW_DIR = ROOT / "tmp"

# Candidate points over the whole sphere. ~29% land, so this lands ~3.8k dots:
# enough for coastlines to read at 560 px, few enough for one instanced draw.
POINT_COUNT = 13000
# Midpoint of the source map's bimodal histogram (land 0-56, open water 255).
THRESHOLD = 128
# Half-width of the sampling patch, in source pixels. Averaging over a patch
# rather than reading one pixel keeps JPEG ringing out of the coastlines.
PATCH = 2

GOLDEN_ANGLE = math.pi * (3.0 - math.sqrt(5.0))

# Illustrative circle for the preview only, so the composition can be judged
# before any component exists. The shipped page carries its own labelled
# synthetic guardians; none of this is real location data.
ORIGIN = (12.97, 77.59, "Bengaluru")
GUARDIANS = [
    (19.08, 72.88, "Mumbai"),
    (28.61, 77.21, "Delhi"),
    (13.08, 80.27, "Chennai"),
    (17.39, 78.49, "Hyderabad"),
    (25.20, 55.27, "Dubai"),
]


def fibonacci_point(index: int, count: int) -> tuple[float, float]:
    """Latitude and longitude in degrees for point `index` of the spiral."""
    # y walks from near +1 to near -1; the half-step inset keeps a point off
    # each exact pole, where longitude is meaningless.
    y = 1.0 - 2.0 * (index + 0.5) / count
    radius = math.sqrt(max(0.0, 1.0 - y * y))
    theta = GOLDEN_ANGLE * index
    x = math.cos(theta) * radius
    z = math.sin(theta) * radius
    return math.degrees(math.asin(y)), math.degrees(math.atan2(x, z))


def main() -> None:
    if not SOURCE.exists():
        raise SystemExit(f"missing source texture: {SOURCE}")

    image = Image.open(SOURCE).convert("L")
    width, height = image.size
    pixels = image.load()

    def luminance(latitude: float, longitude: float) -> float:
        x = (longitude + 180.0) / 360.0 * (width - 1)
        y = (90.0 - latitude) / 180.0 * (height - 1)
        cx, cy = int(round(x)), int(round(y))
        total = 0
        count = 0
        for dy in range(-PATCH, PATCH + 1):
            sy = min(height - 1, max(0, cy + dy))
            for dx in range(-PATCH, PATCH + 1):
                sx = (cx + dx) % width  # longitude wraps
                total += pixels[sx, sy]
                count += 1
        return total / count

    bits: list[int] = []
    land: list[tuple[float, float]] = []

    for index in range(POINT_COUNT):
        lat, lon = fibonacci_point(index, POINT_COUNT)
        is_land = luminance(lat, lon) < THRESHOLD
        bits.append(1 if is_land else 0)
        if is_land:
            land.append((lat, lon))

    # Pack MSB-first; the decoder reads in the same order.
    packed = bytearray((len(bits) + 7) // 8)
    for index, bit in enumerate(bits):
        if bit:
            packed[index >> 3] |= 0x80 >> (index & 7)
    encoded = base64.b64encode(bytes(packed)).decode("ascii")

    OUT_TS.parent.mkdir(parents=True, exist_ok=True)
    OUT_TS.write_text(_render_module(encoded, len(land)), encoding="utf-8")

    _write_previews(land)

    print(f"source      {SOURCE.relative_to(ROOT)} ({width}x{height})")
    print(f"candidates  {POINT_COUNT} (Fibonacci sphere)")
    print(f"land dots   {len(land)} ({len(land) * 100 // POINT_COUNT}%)")
    print(f"payload     {len(packed)} bytes packed, {len(encoded)} base64 chars")
    print(f"wrote       {OUT_TS.relative_to(ROOT)}")
    print(f"previews    {PREVIEW_DIR.relative_to(ROOT)}/globe-*.png")


def _render_module(encoded: str, land_count: int) -> str:
    chunks = [encoded[i : i + 96] for i in range(0, len(encoded), 96)]
    body = "\n".join(f"  '{chunk}' +" for chunk in chunks[:-1])
    body += f"\n  '{chunks[-1]}';"
    return f'''/**
 * Dot-matrix globe land mask. Generated by scripts/bake-globe-land.py from
 * public/textures/earth-specular.jpg, where open water is bright and land dark.
 *
 * Do not edit by hand: re-run the generator instead.
 *
 * Candidate dots are a Fibonacci sphere, a deterministic spiral that spreads
 * points evenly with no rings and no polar bunching. Point i is a pure function
 * of i, so only one bit per point ships: {land_count} land dots out of
 * {POINT_COUNT} candidates, about {len(encoded) // 1024 + 1} KB of base64.
 */

export const POINT_COUNT = {POINT_COUNT};

const GOLDEN_ANGLE = Math.PI * (3 - Math.sqrt(5));

/** Packed land bits, MSB-first, in spiral order. */
const LAND_BITS =
{body}

export interface LandDot {{
  /** Degrees, -90 to 90. */
  lat: number;
  /** Degrees, -180 to 180. */
  lon: number;
}}

let cache: readonly LandDot[] | null = null;

/**
 * Every land dot, decoded once and memoised. Pure data: safe on the server and
 * in a worker, and it touches no DOM.
 */
export function landDots(): readonly LandDot[] {{
  if (cache) return cache;

  const binary = atob(LAND_BITS);
  const dots: LandDot[] = [];

  for (let index = 0; index < POINT_COUNT; index += 1) {{
    const byte = binary.charCodeAt(index >> 3);
    if ((byte & (0x80 >> (index & 7))) === 0) continue;

    const y = 1 - (2 * (index + 0.5)) / POINT_COUNT;
    const radius = Math.sqrt(Math.max(0, 1 - y * y));
    const theta = GOLDEN_ANGLE * index;
    dots.push({{
      lat: (Math.asin(y) * 180) / Math.PI,
      lon: (Math.atan2(Math.cos(theta) * radius, Math.sin(theta) * radius) * 180) / Math.PI,
    }});
  }}

  cache = dots;
  return dots;
}}

/** Unit vector on the sphere. Longitude 0 faces +Z, north pole is +Y. */
export function toVector(lat: number, lon: number): [number, number, number] {{
  const phi = (lat * Math.PI) / 180;
  const theta = (lon * Math.PI) / 180;
  const cosPhi = Math.cos(phi);
  return [cosPhi * Math.sin(theta), Math.sin(phi), cosPhi * Math.cos(theta)];
}}
'''


def _write_previews(land: list[tuple[float, float]]) -> None:
    """Flat and globe previews, so the mask can be judged before it ships."""
    PREVIEW_DIR.mkdir(parents=True, exist_ok=True)

    flat = Image.new("RGB", (1080, 540), (9, 11, 16))
    draw = ImageDraw.Draw(flat)
    for lat, lon in land:
        x = (lon + 180.0) / 360.0 * 1079
        y = (90.0 - lat) / 180.0 * 539
        draw.ellipse((x - 1.1, y - 1.1, x + 1.1, y + 1.1), fill=(226, 232, 240))
    flat.save(PREVIEW_DIR / "globe-flat.png")

    for centre, name in ((77.6, "bengaluru"), (0.0, "atlantic")):
        _write_globe(land, centre, PREVIEW_DIR / f"globe-{name}.png")


def _project(lat: float, lon: float, centre: float, tilt: float, radius: float, size: float):
    phi = math.radians(lat)
    theta = math.radians(lon - centre)
    x = math.cos(phi) * math.sin(theta)
    y = math.sin(phi)
    z = math.cos(phi) * math.cos(theta)
    y2 = y * math.cos(tilt) - z * math.sin(tilt)
    z2 = y * math.sin(tilt) + z * math.cos(tilt)
    return size / 2 + x * radius, size / 2 - y2 * radius, z2


def _write_globe(land: list[tuple[float, float]], centre: float, path: Path) -> None:
    size = 760
    radius = size * 0.42
    tilt = math.radians(16.0)
    globe = Image.new("RGB", (size, size), (9, 11, 16))
    draw = ImageDraw.Draw(globe)

    draw.ellipse(
        (size / 2 - radius, size / 2 - radius, size / 2 + radius, size / 2 + radius),
        outline=(30, 36, 48),
    )

    for lat, lon in land:
        px, py, z = _project(lat, lon, centre, tilt, radius, size)
        if z <= 0.02:
            continue  # far side
        shade = int(96 + 150 * z)
        r = 1.1 + 0.9 * z
        draw.ellipse((px - r, py - r, px + r, py + r), fill=(shade, shade + 4, shade + 10))

    # Illustrative arcs from the origin to each guardian, lifted off the surface.
    ox, oy, oz = _project(ORIGIN[0], ORIGIN[1], centre, tilt, radius, size)
    for glat, glon, _label in GUARDIANS:
        points = []
        for step in range(49):
            t = step / 48
            lat = ORIGIN[0] + (glat - ORIGIN[0]) * t
            lon = ORIGIN[1] + (glon - ORIGIN[1]) * t
            lift = 1.0 + 0.16 * math.sin(math.pi * t)
            px, py, z = _project(lat, lon, centre, tilt, radius * lift, size)
            if z > -0.1:
                points.append((px, py))
        if len(points) > 1:
            draw.line(points, fill=(96, 206, 160), width=2)
        gx, gy, gz = _project(glat, glon, centre, tilt, radius, size)
        if gz > 0:
            draw.ellipse((gx - 4, gy - 4, gx + 4, gy + 4), fill=(96, 206, 160))

    if oz > 0:
        draw.ellipse((ox - 7, oy - 7, ox + 7, oy + 7), outline=(244, 246, 250), width=2)
        draw.ellipse((ox - 3, oy - 3, ox + 3, oy + 3), fill=(244, 246, 250))

    globe.save(path)


if __name__ == "__main__":
    main()
